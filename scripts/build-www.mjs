// Assembles www/ (the folder Capacitor packs into the apps) from web/ and yuyue/.
//
//   www/index.html   tiny router (see below)
//   www/web/         the game, copied as is (minus tools/, data/, README)
//   www/yuyue/       the surprise page; the copy gets an in-app "back to Tabu" button
//
// The game (web/) links to ../yuyue/ and loads ../yuyue/settings.js, so both folders keep
// their relative layout. Capacitor's local web server (Android and iOS) answers every
// path without a file extension, like /yuyue/?open=1, with www/index.html. That file
// therefore sends directory URLs to their own index.html and everything else to the game.
//
// Run: npm run build
import { cp, mkdir, rm, writeFile, readFile, readdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const www = path.join(root, 'www');
const skip = new Set(['tools', 'data', 'README.md', '.DS_Store']);

await rm(www, { recursive: true, force: true });
await mkdir(www, { recursive: true });

for (const dir of ['web', 'yuyue']) {
  await cp(path.join(root, dir), path.join(www, dir), {
    recursive: true,
    filter: (src) => !skip.has(path.basename(src)),
  });
}

// On the web the browser's back button leads from the surprise page to the game. Inside the apps
// there is no browser chrome (and on iOS no back button at all), so the packaged COPY of the page
// gets a small "back to Tabu" button and an Android back-key handler. yuyue/ itself stays untouched.
const backToGame = `<script>
// Added by scripts/build-www.mjs to the packaged copy only.
(function () {
  var C = window.Capacitor;
  if (!C || !C.isNativePlatform || !C.isNativePlatform()) return;
  function home() { if (history.length > 1) history.back(); else location.replace('../web/index.html'); }
  try { var A = C.Plugins && C.Plugins.App; if (A && A.addListener) A.addListener('backButton', home); } catch (e) {}
  var b = document.createElement('button');
  b.type = 'button'; b.textContent = '\\u2039 Tabu'; b.setAttribute('aria-label', 'Tabu');
  b.style.cssText = 'position:fixed;left:12px;top:calc(env(safe-area-inset-top,0px) + 10px);z-index:9999;padding:8px 14px;border-radius:999px;border:1px solid rgba(255,255,255,.35);background:rgba(30,18,38,.6);color:#ffd8e4;font:600 14px system-ui,sans-serif;-webkit-backdrop-filter:blur(8px);backdrop-filter:blur(8px)';
  b.addEventListener('click', home);
  document.addEventListener('DOMContentLoaded', function () { document.body.appendChild(b); });
})();
</script>
`;
const yuyuePage = path.join(www, 'yuyue', 'index.html');
const yuyueHtml = await readFile(yuyuePage, 'utf8');
if (!yuyueHtml.includes('</head>')) throw new Error('yuyue/index.html has no </head>: cannot add the in-app back button');
await writeFile(yuyuePage, yuyueHtml.replace('</head>', backToGame + '</head>'));

await writeFile(path.join(www, 'index.html'), `<!doctype html>
<html lang="tr">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>Tabu</title>
<style>html,body{margin:0;height:100%;background:#f4eee2}</style>
</head>
<body>
<script>
// Generated by scripts/build-www.mjs. Do not edit; edit the script.
(function () {
  var p = location.pathname, q = location.search + location.hash;
  if (p.length > 1 && p.charAt(p.length - 1) === '/') location.replace(p + 'index.html' + q);
  else location.replace('/web/index.html' + (p === '/' ? q : ''));
})();
</script>
</body>
</html>
`);

// The app ships its files inside the package, so the offline service worker is not needed.
// Replace it with one that removes itself, so an old cache can never serve stale files.
await writeFile(path.join(www, 'web', 'sw.js'), `// Generated by scripts/build-www.mjs for the native apps: no offline cache needed.
self.addEventListener('install', () => self.skipWaiting());
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.map((k) => caches.delete(k))))
    .then(() => self.registration.unregister()));
});
`);

const count = async (d) => (await readdir(d, { recursive: true })).length;
console.log(`www/ ready: web (${await count(path.join(www, 'web'))} files), yuyue (${await count(path.join(www, 'yuyue'))} files)`);
